async function seed() {
  const newsCollection = collection(db, 'news');
  for (const item of newsData) {
    await addDoc(newsCollection, {
      ...item,
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp(),
    });
  }
  console.log("Seeding complete!");
  process.exit(0);
}

seed().catch(console.error);
